#ifndef ODRIVE_V36_405_M0_REALTIME_MOTOR_IO_CONFIG_H
#define ODRIVE_V36_405_M0_REALTIME_MOTOR_IO_CONFIG_H

/*
 * TIM1 = 168 MHz，center-aligned ARR=4200：完整 PWM 周期 50 us。
 * CH4 PWM2 上升沿位于峰值前 0.5 us，每完整周期只触发一次 injected pair。
 * ADC = 21 MHz，15-cycle sampling + 12-cycle conversion，名义约 1.29 us。
 * 90% duty 时低边窗口为峰值前后各 2.5 us；仍须 L1/L2 验证实际波形。
 */
#define REALTIME_MOTOR_IO_PWM_PERIOD_COUNTS (4200U)
#define REALTIME_MOTOR_IO_NEUTRAL_COMPARE_COUNTS (2100U)
#define REALTIME_MOTOR_IO_SAMPLE_COMPARE_COUNTS (4116U)
#define REALTIME_MOTOR_IO_TIMER_COUNTS_PER_US (168U)
#define REALTIME_MOTOR_IO_DEAD_TIME_COUNTS (84U)

#define REALTIME_MOTOR_IO_DUTY_MIN (0.10f)
#define REALTIME_MOTOR_IO_DUTY_MAX (0.90f)
#define REALTIME_MOTOR_IO_NORMAL_VOLTAGE_UTILIZATION (0.45f)
#define REALTIME_MOTOR_IO_CONTROL_TIME_TICKS_PER_SECOND (1000000U)
#define REALTIME_MOTOR_IO_FAST_TICK_PERIOD_TICKS (50U)

/* 距离下一 valley update 至少 10 us 才允许写三个 preload，避免跨边界撕裂。 */
#define REALTIME_MOTOR_IO_STAGE_DEADLINE_COUNTS (1680U)
#define REALTIME_MOTOR_IO_SAMPLE_TIMEOUT_US (75U)

#endif
